import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { Vector3 } from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { fitArm } from '../docs/src/weapon-ik.js';

const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/prepare-knife-animations.mjs /path/to/approved-knife-previews');

const loader = new GLTFLoader();
const clips = [];
const rigs = {};
const rightFinger = /^(Index|Middle|Ring|Pinky|Thumb)\dR\.quaternion$/;
// Joint targets in the game's knife mesh coordinates. The imported knuckle
// pose and the wrist attachment supply the rest of the hand silhouette.
const fingerContacts = [
  ['Thumb', 1, [.010, .011, .025]],
  ['Index', 2, [.003, .013, .007]],
  ['Middle', 2, [-.005, .012, .024]],
  ['Ring', 2, [-.008, .012, .044]],
  ['Pinky', 2, [-.015, .012, .061]],
];
for (const sex of ['male', 'female']) {
  const rig = { clips: {} };
  let approvedGrip;
  rigs[sex] = rig;
  for (const [name, preview] of [['Knife_Stab', 'knife-stab-grip'], ['Knife_Cut', 'knife-cut-compact']]) {
    const bytes = await readFile(resolve(source, `${preview}-${sex}.glb`));
    const gltf = await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
    const clip = gltf.animations.find(animation => animation.name === preview);
    const weapon = gltf.scene.getObjectByName('KitWeapon');
    if (!clip || weapon?.parent?.name !== 'WristR') throw new Error(`Missing approved clip or grip: ${preview}/${sex}`);

    const fingers = Object.fromEntries(clip.tracks.filter(track => rightFinger.test(track.name))
      .map(track => [track.name.split('.')[0], Array.from(track.values.slice(0, 4))]));
    const grip = {
      position: weapon.position.toArray(),
      rotation: weapon.quaternion.toArray(),
      scale: weapon.scale.toArray(),
      fingers,
    };
    if (Object.keys(fingers).length !== 19) throw new Error(`Incomplete knife grip: ${preview}/${sex}`);
    if (approvedGrip && JSON.stringify(approvedGrip) !== JSON.stringify(grip)) throw new Error(`Knife grips differ: ${sex}`);
    if (!approvedGrip) {
      approvedGrip = grip;
      for (const [name, rotation] of Object.entries(fingers)) {
        gltf.scene.getObjectByName(name).quaternion.fromArray(rotation);
      }
      gltf.scene.updateMatrixWorld(true);
      for (const [finger, joint, point] of fingerContacts) {
        const [a,b,c] = [joint,joint+1,joint+2].map(i => gltf.scene.getObjectByName(`${finger}${i}R`));
        fitArm(a,b,c,weapon.localToWorld(new Vector3(...point)),b.getWorldPosition(new Vector3()));
      }
      rig.grip = { ...grip, fingers: Object.fromEntries(Object.keys(fingers)
        .map(name => [name, gltf.scene.getObjectByName(name).quaternion.toArray()])) };
    }
    clip.name = `${name}_${sex}`;
    clip.tracks = clip.tracks.filter(track => !rightFinger.test(track.name));
    rig.clips[name] = { name: clip.name, duration: clip.duration };
    const pose = clip.toJSON();
    pose.uuid = `sperrkreis-${pose.name}`;
    for (const track of pose.tracks) track.values = track.values.map(value => Math.round(value * 1e7) / 1e7);
    clips.push(pose);
  }
}

const compressed = gzipSync(JSON.stringify(clips), { level: 9 });
const target = new URL('../docs/src/knife-animations.js', import.meta.url);
const marker = '// Knife animation data generated by scripts/prepare-knife-animations.mjs.';
const previous = await readFile(target, 'utf8');
const boundary = previous.indexOf(marker);
if (boundary < 0) throw new Error('Missing knife data marker in knife-animations.js');
const moduleSource = [
  previous.slice(0, boundary) + marker,
  `export const KNIFE_ANIMATIONS = ${JSON.stringify({ rigs }, null, 2)};`,
  `const PACKED_KNIFE_CLIPS = ${JSON.stringify(compressed.toString('base64'))};`,
  '',
].join('\n');
await writeFile(target, moduleSource);
console.log(`Embedded ${clips.length} knife clips in the game (${compressed.length} bytes before base64).`);
