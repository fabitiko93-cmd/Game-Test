import { readFile, writeFile } from 'node:fs/promises';
import { gzipSync, gunzipSync } from 'node:zlib';
import { AnimationClip, Matrix4, Quaternion, QuaternionKeyframeTrack, Vector3, VectorKeyframeTrack } from 'three';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';
import { QuaterniusAssets } from '../docs/src/quaternius-assets.js';
import { PlayerModels } from '../docs/src/player-models.js';
import { createPlayer } from '../docs/src/character.js';
import { addItem, createItem, equipItem } from '../docs/src/inventory.js';
import { KNIFE_ANIMATIONS } from '../docs/src/knife-animations.js';
import { makeHammerPreview } from './lib/hammer-motion.mjs';

const reference=JSON.parse(await readFile(new URL('./fixtures/melee-grip-reference.json',import.meta.url),'utf8'));
const loader=new GLTFLoader();
const library=new QuaterniusAssets({loadAsset:async url=>{
  const filename=new URL(url).pathname.split('/').at(-1);
  const bytes=gunzipSync(await readFile(new URL('../docs/assets/quaternius/'+filename,import.meta.url)));
  return loader.parseAsync(Uint8Array.from(bytes).buffer,'');
}});
const models=new PlayerModels({},library);
await models.ready;
const clips=[],grips={claw_hammer:{},kitchen_knife:{}};
for(const sex of ['male','female']){
  const actor=await makeHammerPreview(models,sex,reference[sex].hammer);
  grips.claw_hammer[sex]=actor.grip;
  const bones=[];
  actor.entity.model.traverse(node=>{if(node.isBone)bones.push(node);});
  const samples=216, times=[];
  const positions=new Map(bones.map(b=>[b,[]]));
  const rotations=new Map(bones.map(b=>[b,[]]));
  for(let frame=0;frame<=samples;frame++){
    const t=actor.duration*frame/samples;
    actor.pose(t);
    times.push(t);
    for(const bone of bones){
      positions.get(bone).push(...bone.position.toArray());
      const q=bone.quaternion.clone().normalize();
      const previous=rotations.get(bone);
      if(previous.length&&q.dot(new Quaternion().fromArray(previous,previous.length-4))<0)q.set(-q.x,-q.y,-q.z,-q.w);
      previous.push(...q.toArray());
    }
  }
  const tracks=bones.flatMap(b=>[
    new VectorKeyframeTrack(b.name+'.position',times,positions.get(b)),
    new QuaternionKeyframeTrack(b.name+'.quaternion',times,rotations.get(b)),
  ]);
  const idleTracks=tracks.map(track=>{
    const value=Array.from(track.createInterpolant().evaluate(0));
    return new track.constructor(track.name,[0,1],[...value,...value]);
  });
  const idle=new AnimationClip('Hammer_Idle_'+sex,1,idleTracks).optimize().toJSON();
  idle.uuid='sperrkreis-'+idle.name;
  clips.push(idle);
  grips.claw_hammer[sex].carry=Object.fromEntries(['ShoulderR','UpperArmR','LowerArmR','WristR'].map(name=>[
    name,Array.from(tracks.find(track=>track.name===name+'.quaternion').values.slice(0,4)),
  ]));
  const clip=new AnimationClip('Hammer_Slash_'+sex,actor.duration,tracks).optimize().toJSON();
  clip.uuid='sperrkreis-'+clip.name;
  for(const track of clip.tracks)track.values=track.values.map(value=>Math.round(value*1e7)/1e7);
  clips.push(clip);

  // Recover the approved cooking-knife placement from its original wrist pose.
  const player=createPlayer({appearance:{sex}});
  const knife=createItem('kitchen_knife');addItem(player,knife);equipItem(player,knife.id);
  const entity=models.prepare(player,0);
  models.pose(entity,{clip:'Knife_Stab',progress:0,delta:1,yaw:0});
  const wrist=entity.model.getObjectByName('WristR');
  const approved=reference[sex].knife;
  const world=new Matrix4().compose(new Vector3().fromArray(approved.position),new Quaternion().fromArray(approved.rotation),new Vector3(1,1,1))
    .multiply(new Matrix4().makeTranslation(...approved.knifeOffset));
  const matrix=wrist.matrixWorld.clone().invert().multiply(world);
  const position=new Vector3(),rotation=new Quaternion(),scale=new Vector3();
  matrix.decompose(position,rotation,scale);
  grips.kitchen_knife[sex]={position:position.toArray(),rotation:rotation.toArray(),scale:scale.toArray(),
    fingers:{...KNIFE_ANIMATIONS.rigs[sex].grip.fingers,...reference[sex].knifeFingers}};
}
const rounded=JSON.parse(JSON.stringify(grips,(_,v)=>typeof v==='number'?Math.round(v*1e8)/1e8:v));
await writeFile(new URL('../docs/assets/weapons/melee-grips.json',import.meta.url),JSON.stringify(rounded)+'\n');
const packed=gzipSync(JSON.stringify(clips),{level:9}).toString('base64');
const header=`import { bindOneShotAnimation, unpackAnimationClips } from './packed-animation.js';

export const HAMMER_ANIMATION = { name: 'Hammer_Slash', duration: 1.08, contact: .50 };
let clips;
export function bindHammerAnimation(entity) {
  if (entity.actions.has(HAMMER_ANIMATION.name)) return;
  clips ??= unpackAnimationClips(PACKED_HAMMER_CLIPS);
  for (const name of [HAMMER_ANIMATION.name, 'Hammer_Idle']) {
    bindOneShotAnimation(entity, name, clips.get(name+'_'+entity.modelSex));
  }
}

// Generated by scripts/prepare-hammer-animations.mjs from the approved authored motion.
`;
await writeFile(new URL('../docs/src/hammer-animations.js',import.meta.url),header+`const PACKED_HAMMER_CLIPS = ${JSON.stringify(packed)};\n`);
console.log('Baked both hammer rigs and weapon grips',Buffer.byteLength(packed),'base64 bytes');
