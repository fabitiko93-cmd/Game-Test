import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { gzipSync } from 'node:zlib';
import { GLTFLoader } from 'three/addons/loaders/GLTFLoader.js';

const source = process.argv[2];
if (!source) throw new Error('Usage: node scripts/prepare-punch-animations.mjs /path/to/approved-punch-previews');

const loader = new GLTFLoader();
const name = 'Punch_OneTwo';
const clips = [];
for (const sex of ['male', 'female']) {
  const bytes = await readFile(resolve(source, `soft-legs-${sex}.glb`));
  const gltf = await loader.parseAsync(bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength), '');
  const clip = gltf.animations.find(animation => animation.name === 'EinsZweiWeich');
  if (!clip) throw new Error(`Missing approved 1–2 clip: ${sex}`);
  clip.name = `${name}_${sex}`;
  const pose = clip.optimize().toJSON();
  pose.uuid = `sperrkreis-${pose.name}`;
  for (const track of pose.tracks) track.values = track.values.map(value => Math.round(value * 1e7) / 1e7);
  clips.push(pose);
}

const duration = clips[0].duration;
if (clips[1].duration !== duration) throw new Error('Punch clips have different durations');
const packed = gzipSync(JSON.stringify(clips), { level: 9 });
const target = new URL('../docs/src/punch-animations.js', import.meta.url);
const marker = '// Punch animation data generated by scripts/prepare-punch-animations.mjs.';
const previous = await readFile(target, 'utf8');
const boundary = previous.indexOf(marker);
if (boundary < 0) throw new Error('Missing punch data marker in punch-animations.js');
await writeFile(target, [
  previous.slice(0, boundary) + marker,
  `export const PUNCH_ANIMATION = ${JSON.stringify({ name, duration })};`,
  `const PACKED_PUNCH_CLIPS = ${JSON.stringify(packed.toString('base64'))};`,
  '',
].join('\n'));
